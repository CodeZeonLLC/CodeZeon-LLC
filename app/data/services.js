export function getService(slug) {
  return services.find((service) => service.slug === slug);
}

export function getServiceOfferings(category) {
  const list = category ? [category] : services;
  return list.flatMap((service) =>
    service.offerings.map((offering) => ({
      title: offering.title,
      text: offering.text,
      category: service.title,
      categorySlug: service.slug,
    })),
  );
}

export function countOfferings(service) {
  return service.offerings.length;
}
